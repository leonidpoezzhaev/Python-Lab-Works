'''Graf2. Дано описание неориентированного графа в текстовом файле с именем FileName1_1 в виде матрицы смежности. Первая строка
файла содержит количество вершин графа(n) , а следующие n строк содержат матрицу смежности (a), a[i][j]=0, если ребра между
вершинами i и j не существует. Построить матрицу инцидентности данного графа и вывести ее в файл с именем FileName1_2. Для
справки: матрица инцидентности (b) имеет размер n x m, m - число ребер графа, b[i][j]=1, если ребро j инцидентно вершине i,
в противном случае b[i][j]=0. Нумерацию ребер осуществлять в следующем порядке: сначала ребра, инцидентные вершине номер 1,
потом ребра инцидентные вершине номер 2 и т.д. до вершины номер n. Ребра, инцидентные вершине с номером i перечислять в
порядке возрастания номера второй вершины, инцидентной данному ребру. При выводе в первой строке указать размер матрицы
инцидентности: числа n и m, а в следующих n строках разместить матрицу инцидентности.'''

with open('FileName1_1.txt', 'r') as infile:
    lines = infile.read().strip().splitlines()
n = int(lines[0])
adj = [list(map(int, line.split())) for line in lines[1:1+n]]

edges = []
for i in range(n):
    for j in range(i + 1, n):
        if adj[i][j] == 1:
            edges.append((i, j))
m = len(edges)

inc = [[0] * m for _ in range(n)]
for e, (i, j) in enumerate(edges):
    inc[i][e] = 1
    inc[j][e] = 1

with open('FileName1_2.txt', 'w') as outfile:
    outfile.write(f"{n} {m}\n")
    for row in inc:
        outfile.write(' '.join(map(str, row)) + '\n')