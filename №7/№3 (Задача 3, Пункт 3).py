'''Задача 3. Напишите программу для решения СЛАУ с использованием
библиотеки NumPy. Результат решения вывести в виде вектора. Сделать
проверку
4x1 - 3x2 + 5x3 = -3
3x1 - 2x2 + 8x3 = -6
x1 - 7x2 - 5x3 = -7'''

import numpy as np

A = np.array([[4, -3, 5], [3, -2, 8], [1, -7, -5]], dtype=int)
b = np.array([-3, -6, -7], dtype=int)

x = np.linalg.solve(A, b)

print("Ответ:", *x)

#проверка
print(np.allclose(A @ x, b))
