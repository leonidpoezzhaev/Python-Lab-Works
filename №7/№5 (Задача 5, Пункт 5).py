'''Задача 5.
1. Туристическая популярность городов в России (не менее пяти,
данные сформировать самостоятельно).
2. Сгенерировать случайное распределение из 1200 точек с
координатами (x, y). Каждая координата – случайное вещественное
число в диапазоне [-5.2; 20.7] с равномерным распределением. '''

import numpy as np
import matplotlib.pyplot as plt

# 1) Популярность городов (данные сформированы вручную, примерные проценты)
networks = ['Москва', 'Санкт-Петербург', 'Сочи', 'Казань', 'Севастополь', 'Остальные']
popularity = [30, 20, 8, 6, 4, 32]  # примерные доли в процентах (сумма = 100)

# figsize — размер рисунка в дюймах (ширина, высота). Здесь выбран компактный прямоугольник.
plt.figure(figsize=(8, 4))

# bar — строим столбчатую диаграмму: по оси X подписи сетей, по Y — их популярность.
# color — массив цветов для столбцов, можно задать как единый цвет или индивидуально.
bars = plt.bar(networks, popularity, color=['#4C72B0','#55A868','#C44E52','#8172B3','#CCB974','#64B5CD'])

# Заголовок и подписи осей
plt.title('Популярность социальных сетей в России')
plt.xlabel('Социальная сеть')
plt.ylabel('Доля, %')

# Ограничение по оси Y для аккуратного отображения надписей над столбцами
plt.ylim(0, max(popularity) + 10)

# Подписываем значения над каждым столбиком
# Для каждого столбца получаем его x-позицию и ширину, чтобы правильно разместить текст
for bar, val in zip(bars, popularity):
    plt.text(bar.get_x() + bar.get_width()/2, val + 1, f'{val}%', ha='center', va='bottom')

# Дополнительная сетка по горизонтали для удобства чтения значений
plt.grid(axis='y', linestyle='--', alpha=0.3)

# tight_layout — автоматически подбирает отступы, чтобы подписи не обрезались
plt.tight_layout()
# Показываем график
plt.show()

# Построение круговой диаграммы
# figsize — делаем квадратную фигуру, чтобы круг выглядел ровно
plt.figure(figsize=(6, 6))

# Повторно определяем массив цветов для согласованности оформления
colors = ['#4C72B0','#55A868','#C44E52','#8172B3','#CCB974','#64B5CD']

explode = [0.05 if v == max(popularity) else 0 for v in popularity]  # выделить самый крупный сектор

# plt.pie строит круговую диаграмму
# labels — подписи с названиями сетей
# autopct — формат отображения процентов внутри секторов
# startangle — угол поворота, чтобы расположить сектора более эстетично
# shadow — небольшая тень для объёма
plt.pie(popularity, labels=networks, autopct='%1.1f%%', startangle=140, colors=colors, explode=explode, shadow=True)

plt.title('Доля социальных сетей в России (круговая диаграмма)')

# axis('equal') делает оси равными, чтобы круг не искажается (становится кругом, а не эллипсом)
plt.axis('equal')

plt.tight_layout()
plt.show()

# 2) Сгенерировать случайное распределение из 1500 точек (x, y), координаты – целые в [0, 20]

np.random.seed(42)

n_points = 1200
low, high = -5.2, 20.7

# Генерация x-координат: равномерное распределение на отрезке [low, high].
# np.random.uniform(a, b, size) возвращает массив указанного размера со значениями в [a, b).
x = np.random.uniform(low, high, n_points)
y = np.random.uniform(low, high, n_points)

# figsize задает размер в дюймах (ширина, высота). Это влияет на итоговое разрешение рисунка.
plt.figure(figsize=(8, 6))
# s — размер маркера в точках (пикселях на устройстве отображения).
plt.scatter(x, y, s=10, alpha=0.6, c='tab:green', edgecolors='none')
plt.title('Случайное распределение 1200 точек в диапазоне [-5.2, 20.7]')
plt.xlabel('x')
plt.ylabel('y')
plt.grid(True)
plt.axis('equal')  # одинаковый масштаб по осям
plt.show()
